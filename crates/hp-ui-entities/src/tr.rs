#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_clean() {
        let problems = hp_app::i18n::lint_table(TR);
        assert!(problems.is_empty(), "{problems:#?}");
    }

    #[test]
    fn no_collision_with_core_keys() {
        for (key, _, _) in TR {
            assert!(!hp_app::strings::TR.iter().any(|(k, _, _)| k == key), "{key} is already a core key");
            assert!(key.starts_with("entities."), "{key} must use the crate prefix");
        }
    }

    #[test]
    fn placeholders_match() {
        for (key, en, fr) in TR {
            for i in 0..4 {
                let p = format!("{{{i}}}");
                assert_eq!(en.contains(&p), fr.contains(&p), "{key}: placeholder {p} differs");
            }
        }
    }
}
